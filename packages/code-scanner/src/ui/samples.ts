/** The sample as an RGBA image: `module` px per module and `quiet` modules of white around it. */
export function sampleImage(module: number = 8, quiet: number = 4): ScanImage {
  const size = (SAMPLE_QR.size + 2 * quiet) * module, data = new Uint8ClampedArray(size * size * 4);
  for (let y = 0; y < size; y++) {
    for (let x = 0; x < size; x++) {
      const mx = Math.floor(x / module) - quiet, my = Math.floor(y / module) - quiet;
      const dark = mx >= 0 && my >= 0 && mx < SAMPLE_QR.size && my < SAMPLE_QR.size && SAMPLE_QR.rows[my]![mx] === "1";
      const i = (y * size + x) * 4;
      data[i] = data[i + 1] = data[i + 2] = dark ? 0 : 255;
      data[i + 3] = 255;
    }
  }
  return { width: size, height: size, data, format: "rgba" };
}
